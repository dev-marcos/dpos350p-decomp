#include "fatfs/ff_stock.h"

DWORD ld_dword(const BYTE *ptr)
{
    DWORD rv;

    rv = ptr[3];
    rv = rv << 8 | ptr[2];
    rv = rv << 8 | ptr[1];
    rv = rv << 8 | ptr[0];
    return rv;
}
