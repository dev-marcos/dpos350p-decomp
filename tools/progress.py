#!/usr/bin/env python3
"""Decompilation progress -> docs/PROGRESS.md

Levels per function:
  MATCHING    C in src/ that compiles to the exact original bytes (needs the original
              compiler: Arm Compiler 5, unlicensed here -> currently always 0)
  EQUIVALENT  C in nonmatching/ whose behaviour matches the stock function under
              tools/emu (build/emu/results.json, status EQUIVALENT)
  NONMATCHING C in nonmatching/ not (yet) verified, or failing
  ASM         only the generated assembly in asm/
"""
import csv
import json
import re
from collections import defaultdict
from datetime import date
from pathlib import Path
try:
    from tools import srcindex                # noqa: E402
except ImportError:                           # run as a script from tools/
    import srcindex                           # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
AREAS = [(0x40019AF4, 0x4006DDEC, "main code"), (0x4008CB28, 0x4008CFB8, "startup")]


def main():
    m = json.loads((ROOT / "build/analysis/map.json").read_text())
    names = {int(r["address"], 16): r["name"] for r in csv.DictReader(open(ROOT / "symbols/symbols_2025-06-19.csv"))}
    funcs = {f["start"]: f["end"] - f["start"] for f in m["functions"]}
    res_path = ROOT / "build/emu/results.json"
    results = {int(k, 16): v for k, v in json.loads(res_path.read_text()).items()} if res_path.exists() else {}
    src = set(srcindex.sources("src")) if (ROOT / "src").exists() else set()
    nonm = srcindex.sources()

    def level(a):
        if a in src:
            return "MATCHING"
        if a in nonm:
            return "EQUIVALENT" if results.get(a, {}).get("status") == "EQUIVALENT" else "NONMATCHING"
        return "ASM"

    tot = defaultdict(lambda: [0, 0])
    area = defaultdict(lambda: defaultdict(lambda: [0, 0]))
    for a, size in funcs.items():
        lv = level(a)
        tot[lv][0] += 1; tot[lv][1] += size
        an = next((n for lo, hi, n in AREAS if lo <= a < hi), "other")
        area[an][lv][0] += 1; area[an][lv][1] += size
    nf, nb = len(funcs), sum(funcs.values())

    def pct(x, y):
        return f"{100 * x / y:.2f}%" if y else "-"
    L = ["# Decompilation progress", "",
         f"Generated by `tools/progress.py` on {date.today().isoformat()} (build 2025-06-19).", "",
         "The build always ships `asm/`; C never changes the ISO. Levels (see `docs/COMPILER.md` §6):", "",
         "- **MATCHING**: C in `src/` that compiles to the original bytes (needs Arm Compiler 5,",
         "  which is unlicensed here, so this is 0 by construction).",
         "- **EQUIVALENT**: C in `nonmatching/` whose observable behaviour (return value, memory",
         "  writes, calls to stubbed I/O) matches the stock function under `tools/emu`.",
         "- **NONMATCHING**: C written but not verified, or failing.",
         "- **ASM**: only generated assembly.", "",
         "## Totals", "", "| level | functions | % | code bytes | % |", "|---|---:|---:|---:|---:|"]
    for lv in ("MATCHING", "EQUIVALENT", "NONMATCHING", "ASM"):
        n, b = tot[lv]
        L.append(f"| {lv} | {n} | {pct(n, nf)} | {b} | {pct(b, nb)} |")
    L.append(f"| **total** | {nf} | | {nb} | |")
    L += ["", "## By area", "", "| area | functions | C (equiv+match) | code bytes | C bytes |", "|---|---:|---:|---:|---:|"]
    for an in [n for _, _, n in AREAS] + ["other"]:
        d = area[an]
        n = sum(v[0] for v in d.values()); b = sum(v[1] for v in d.values())
        c = d["EQUIVALENT"][0] + d["MATCHING"][0]; cb = d["EQUIVALENT"][1] + d["MATCHING"][1]
        if n:
            L.append(f"| {an} | {n} | {c} ({pct(c, n)}) | {b} | {cb} ({pct(cb, b)}) |")
    L += ["", "## Functions with C", "", "| address | name | size | level | cases | source |", "|---|---|---:|---|---:|---|"]
    for a in sorted(nonm.keys() | src):
        r = results.get(a, {})
        L.append(f"| `0x{a:08X}` | {names.get(a, r.get('name', '?'))} | {funcs.get(a, 0)} | {level(a)} | "
                 f"{r.get('cases', '-')} | `{(nonm.get(a) or '').relative_to(ROOT).as_posix() if a in nonm else 'src'}` |")
    (ROOT / "docs/PROGRESS.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[13:20]))


if __name__ == "__main__":
    main()
